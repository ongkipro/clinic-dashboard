CREATE FUNCTION public.followup_scan(p_today date DEFAULT NULL) RETURNS integer
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  t record;
  c record;
  v_now timestamptz := clock_timestamp();
  r record;
  v_today date;
  v_exp date;
  v_d integer;
  v_k integer;
  v_paid bigint;
  v_n integer := 0;
BEGIN
  IF public.app_tenant_id() IS NOT NULL OR public.app_staff_id() IS NOT NULL THEN
    RAISE EXCEPTION 'followup_scan runs on an unbound worker connection only' USING ERRCODE = '42501';
  END IF;
  FOR t IN SELECT tr.id AS tenant_id FROM public.tenants_registry tr WHERE tr.lifecycle_state IN ('onboarding','live','suspended') ORDER BY tr.id LOOP
    PERFORM pg_advisory_xact_lock(hashtextextended('staff_access:' || t.tenant_id::text, 0));
    -- control_due (Scenario PR-30): a scheduled free control whose source line is issued and not refunded, from control_date − 2 to valid_until
    FOR c IN SELECT cc.id, cc.branch_id, cc.patient_id, cc.control_date, cc.valid_until, il.invoice_id, il.plan_item_id
               FROM public.consultation_controls cc
               JOIN public.invoice_lines il ON il.tenant_id = cc.tenant_id AND il.id = cc.invoice_line_id
               JOIN public.invoices i ON i.tenant_id = il.tenant_id AND i.id = il.invoice_id AND i.state = 'issued'
              WHERE cc.tenant_id = t.tenant_id AND cc.state = 'scheduled'
                AND NOT public.consultation_line_refunded(cc.tenant_id, cc.invoice_line_id, NULL, 0) LOOP
      v_today := coalesce(p_today, public.followup_branch_today(t.tenant_id, c.branch_id, v_now));
      CONTINUE WHEN v_today < c.control_date - 2 OR v_today > c.valid_until;
      v_n := v_n + public.followup_create(t.tenant_id, c.branch_id, c.patient_id, 'control_due', 'consultation_control', c.id, 'due', 'bc',
        public.followup_guiding_bc(t.tenant_id, c.patient_id, c.invoice_id,
          (SELECT pi.plan_id FROM public.plan_items pi WHERE pi.tenant_id = t.tenant_id AND pi.id = c.plan_item_id), c.branch_id, v_now),
        c.control_date - 2, v_now);
    END LOOP;
    -- package_stage (DEC-105): an active, unexpired package with ≥1 redeemed, ≥1 available and no reserved session; the next available session
    -- is due 30 days after the last redemption (a fixed rule, revisable by decision).
    FOR c IN SELECT pk.id, pk.sold_branch_id AS branch_id, pk.patient_id, pk.invoice_id,
                    (SELECT max(s.redeemed_at) FROM public.package_sessions s WHERE s.tenant_id = pk.tenant_id AND s.package_id = pk.id AND s.state = 'redeemed') AS last_at,
                    (SELECT min(s.seq) FROM public.package_sessions s WHERE s.tenant_id = pk.tenant_id AND s.package_id = pk.id AND s.state = 'available') AS next_seq
               FROM public.packages pk
              WHERE pk.tenant_id = t.tenant_id AND pk.state = 'active' AND pk.validity_end > v_now
                AND EXISTS (SELECT 1 FROM public.package_sessions s WHERE s.tenant_id = pk.tenant_id AND s.package_id = pk.id AND s.state = 'redeemed')
                AND EXISTS (SELECT 1 FROM public.package_sessions s WHERE s.tenant_id = pk.tenant_id AND s.package_id = pk.id AND s.state = 'available')
                AND NOT EXISTS (SELECT 1 FROM public.package_sessions s WHERE s.tenant_id = pk.tenant_id AND s.package_id = pk.id AND s.state = 'reserved') LOOP
      v_today := coalesce(p_today, public.followup_branch_today(t.tenant_id, c.branch_id, v_now));
      CONTINUE WHEN v_today < public.followup_branch_today(t.tenant_id, c.branch_id, c.last_at) + 30;
      v_n := v_n + public.followup_create(t.tenant_id, c.branch_id, c.patient_id, 'package_stage', 'package', c.id, 'stage_' || c.next_seq, 'bc',
        public.followup_guiding_bc(t.tenant_id, c.patient_id, c.invoice_id, NULL, c.branch_id, v_now),
        public.followup_branch_today(t.tenant_id, c.branch_id, c.last_at) + 30, v_now);
    END LOOP;
    -- package_expiry (SET-23): the smallest threshold d already crossed while unused sessions remain; an earlier still-open expiry step of the
    -- package is closed by the scan (dismissed, diganti — no staff).
    FOR c IN SELECT pk.id, pk.sold_branch_id AS branch_id, pk.patient_id, pk.invoice_id, pk.validity_end
               FROM public.packages pk
              WHERE pk.tenant_id = t.tenant_id AND pk.state = 'active' AND pk.validity_end > v_now
                AND EXISTS (SELECT 1 FROM public.package_sessions s WHERE s.tenant_id = pk.tenant_id AND s.package_id = pk.id AND s.state IN ('available','reserved')) LOOP
      v_today := coalesce(p_today, public.followup_branch_today(t.tenant_id, c.branch_id, v_now));
      v_exp := public.followup_branch_today(t.tenant_id, c.branch_id, c.validity_end);
      SELECT min(d) INTO v_d FROM (SELECT (x #>> '{}')::integer AS d FROM jsonb_array_elements(public.followup_setting(t.tenant_id, 'SET-23', v_now)) x) th
       WHERE v_today >= v_exp - d;
      CONTINUE WHEN v_d IS NULL OR v_today > v_exp;
      v_k := public.followup_create(t.tenant_id, c.branch_id, c.patient_id, 'package_expiry', 'package', c.id, 'd' || v_d, 'bc',
        public.followup_guiding_bc(t.tenant_id, c.patient_id, c.invoice_id, NULL, c.branch_id, v_now), v_exp - v_d, v_now);
      v_n := v_n + v_k;
      UPDATE public.followups SET state = 'dismissed', outcome = 'diganti', closed_at = v_now, updated_at = v_now
       WHERE tenant_id = t.tenant_id AND rule_code = 'package_expiry' AND source_id = c.id AND state = 'open' AND step <> 'd' || v_d;
    END LOOP;
    -- instalment_locked: an active package schedule whose package still has an available session; each row past due and not covered by
    -- what was paid since the schedule was set (the T-083 coverage rule).
    FOR c IN SELECT s.id AS schedule_id, s.branch_id, s.patient_id, s.package_id, s.base_paid
               FROM public.instalment_schedules s JOIN public.packages pk ON pk.tenant_id = s.tenant_id AND pk.id = s.package_id AND pk.state = 'active'
              WHERE s.tenant_id = t.tenant_id AND s.state = 'active' AND s.package_id IS NOT NULL
                AND EXISTS (SELECT 1 FROM public.package_sessions ps WHERE ps.tenant_id = pk.tenant_id AND ps.package_id = pk.id AND ps.state = 'available') LOOP
      v_today := coalesce(p_today, public.followup_branch_today(t.tenant_id, c.branch_id, v_now));
      v_paid := public.instalment_target_paid(t.tenant_id, c.package_id, NULL) - c.base_paid;
      FOR r IN SELECT x.id, x.due_on, sum(x.amount) OVER (ORDER BY x.seq) AS cum FROM public.instalment_rows x
                WHERE x.tenant_id = t.tenant_id AND x.schedule_id = c.schedule_id ORDER BY x.seq LOOP
        CONTINUE WHEN r.due_on >= v_today OR v_paid >= r.cum;
        v_n := v_n + public.followup_create(t.tenant_id, c.branch_id, c.patient_id, 'instalment_locked', 'instalment_row', r.id, 'overdue', 'cs',
          NULL, r.due_on, v_now);
      END LOOP;
    END LOOP;
    -- receivable: an open receivable with a remaining amount; with an active schedule each uncovered row due by today, else one 'open' step.
    FOR c IN SELECT rc.id, rc.branch_id, rc.patient_id, rc.collected_amount, rc.created_at,
                    (SELECT s.id FROM public.instalment_schedules s WHERE s.tenant_id = rc.tenant_id AND s.receivable_id = rc.id AND s.state = 'active') AS schedule_id,
                    (SELECT s.base_paid FROM public.instalment_schedules s WHERE s.tenant_id = rc.tenant_id AND s.receivable_id = rc.id AND s.state = 'active') AS base_paid
               FROM public.receivables rc
              WHERE rc.tenant_id = t.tenant_id AND rc.state = 'open' AND rc.amount - rc.collected_amount - rc.written_off_amount > 0 LOOP
      v_today := coalesce(p_today, public.followup_branch_today(t.tenant_id, c.branch_id, v_now));
      IF c.schedule_id IS NULL THEN
        v_n := v_n + public.followup_create(t.tenant_id, c.branch_id, c.patient_id, 'receivable', 'receivable', c.id, 'open', 'cs', NULL,
          public.followup_branch_today(t.tenant_id, c.branch_id, c.created_at), v_now);
      ELSE
        FOR r IN SELECT x.seq, x.due_on, sum(x.amount) OVER (ORDER BY x.seq) AS cum FROM public.instalment_rows x
                  WHERE x.tenant_id = t.tenant_id AND x.schedule_id = c.schedule_id ORDER BY x.seq LOOP
          CONTINUE WHEN r.due_on > v_today OR c.collected_amount - c.base_paid >= r.cum;
          v_n := v_n + public.followup_create(t.tenant_id, c.branch_id, c.patient_id, 'receivable', 'receivable', c.id, 'row_' || r.seq, 'cs', NULL,
            r.due_on, v_now);
        END LOOP;
      END IF;
    END LOOP;
    -- plan_unselected (SET-22 kunjungan_kedua): an active plan with a non-removed item neither selected nor on an issued invoice line, the
    -- window after the plan's date passed.
    v_k := (public.followup_setting(t.tenant_id, 'SET-22', v_now) ->> 'kunjungan_kedua')::integer;
    FOR c IN SELECT cp.id, cp.branch_id, cp.patient_id, cp.created_at FROM public.care_plans cp
              WHERE cp.tenant_id = t.tenant_id AND cp.state = 'active'
                AND EXISTS (SELECT 1 FROM public.plan_items pi WHERE pi.tenant_id = cp.tenant_id AND pi.plan_id = cp.id AND pi.removed_at IS NULL
                  AND coalesce((SELECT sum(si.quantity) FROM public.selection_items si WHERE si.tenant_id = pi.tenant_id AND si.plan_item_id = pi.id), 0) < pi.qty
                  AND NOT EXISTS (SELECT 1 FROM public.invoice_lines il JOIN public.invoices i ON i.tenant_id = il.tenant_id AND i.id = il.invoice_id AND i.state = 'issued'
                                   WHERE il.tenant_id = pi.tenant_id AND il.plan_item_id = pi.id)) LOOP
      v_today := coalesce(p_today, public.followup_branch_today(t.tenant_id, c.branch_id, v_now));
      CONTINUE WHEN v_today < public.followup_branch_today(t.tenant_id, c.branch_id, c.created_at) + v_k;
      v_n := v_n + public.followup_create(t.tenant_id, c.branch_id, c.patient_id, 'plan_unselected', 'care_plan', c.id, 'unselected', 'bc',
        public.followup_guiding_bc(t.tenant_id, c.patient_id, NULL, c.id, c.branch_id, v_now),
        public.followup_branch_today(t.tenant_id, c.branch_id, c.created_at) + v_k, v_now);
    END LOOP;
    -- dormant (SET-22 tidak_datang): a canonical patient with a closed visit, no open visit and no live appointment in the cluster, the last
    -- visit older than the threshold; keyed to that last visit (a later visit and a new dormancy make a new step).
    v_k := (public.followup_setting(t.tenant_id, 'SET-22', v_now) ->> 'tidak_datang')::integer;
    FOR c IN SELECT pt.id AS patient_id, lv.id AS visit_id, lv.branch_id, lv.checked_in_at
               FROM public.patients pt
               CROSS JOIN LATERAL (SELECT v.id, v.branch_id, v.checked_in_at FROM public.visits v
                                    WHERE v.tenant_id = pt.tenant_id AND v.patient_id = ANY (public.patient_cluster(pt.tenant_id, pt.id))
                                    ORDER BY v.checked_in_at DESC, v.id DESC LIMIT 1) lv
              WHERE pt.tenant_id = t.tenant_id AND NOT public.patient_is_merged(pt.tenant_id, pt.id)
                AND NOT EXISTS (SELECT 1 FROM public.visits v WHERE v.tenant_id = pt.tenant_id AND v.patient_id = ANY (public.patient_cluster(pt.tenant_id, pt.id))
                                 AND v.closed_at IS NULL)
                AND NOT EXISTS (SELECT 1 FROM public.appointments ap WHERE ap.tenant_id = pt.tenant_id AND ap.patient_id = ANY (public.patient_cluster(pt.tenant_id, pt.id))
                                 AND public.appointment_live(ap)) LOOP
      v_today := coalesce(p_today, public.followup_branch_today(t.tenant_id, c.branch_id, v_now));
      CONTINUE WHEN v_today <= public.followup_branch_today(t.tenant_id, c.branch_id, c.checked_in_at) + v_k;
      v_n := v_n + public.followup_create(t.tenant_id, c.branch_id, c.patient_id, 'dormant', 'patient', c.patient_id,
        'visit_' || replace(c.visit_id::text, '-', ''), 'cs', NULL, public.followup_branch_today(t.tenant_id, c.branch_id, c.checked_in_at) + v_k + 1, v_now);
    END LOOP;
  END LOOP;
  RETURN v_n;
END
$$;--> statement-breakpoint
