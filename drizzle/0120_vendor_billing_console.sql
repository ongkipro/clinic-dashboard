-- constant-time equality of two hex digests
CREATE FUNCTION public.vendor_billing_hash_eq(a text, b text) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  d integer := 0;
  i integer;
BEGIN
  IF a IS NULL OR b IS NULL OR length(a) <> length(b) THEN RETURN false; END IF;
  FOR i IN 1..length(a) LOOP
    d := d | (ascii(substr(a, i, 1)) # ascii(substr(b, i, 1)));
  END LOOP;
  RETURN d = 0;
END
$$;--> statement-breakpoint
