-- T-098 (plan r1 §3-§5): survey_record — the bound command; a low score (<= 2) creates the manager's follow-up in the same transaction
-- (PR-78) and is not review-eligible; review_eligible = score >= 4 (no send in T-098).
CREATE FUNCTION public.survey_record(p_key text, p jsonb) RETURNS uuid
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  a record;
  v public.visits;
  s public.surveys;
  v_score integer;
  v_id uuid;
  v_patient uuid;
  v_mgr uuid;
  v_fu uuid;
  v_now timestamptz;
BEGIN
  SELECT x.tenant_id, x.staff_id, x.role, x.branch_id INTO a FROM public.tenant_actor_lock() x;
  IF a.role NOT IN ('owner','central_cs','manager') THEN
    RAISE EXCEPTION 'ERR_FORBIDDEN: role may not record surveys' USING ERRCODE = '42501';
  END IF;
  IF NOT public.tenant_capability('care_message') THEN
    RAISE EXCEPTION 'ERR_TENANT_SUSPENDED' USING ERRCODE = '42501';
  END IF;
  -- visit_id must be a UUID string (review r1 P2: a malformed id answers ERR_INVALID_INPUT, never a raw cast error)
  IF jsonb_typeof(p) IS DISTINCT FROM 'object' OR p - 'visit_id' - 'score' <> '{}'::jsonb OR jsonb_typeof(p -> 'score') IS DISTINCT FROM 'number'
     OR (p ->> 'score') !~ '^[1-5]$' OR coalesce(p_key, '') !~ '^[A-Za-z0-9_.:-]{8,128}$'
     OR jsonb_typeof(p -> 'visit_id') IS DISTINCT FROM 'string'
     OR (p ->> 'visit_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: survey' USING ERRCODE = '22023';
  END IF;
  v_score := (p ->> 'score')::integer;
  SELECT * INTO s FROM public.surveys x WHERE x.tenant_id = a.tenant_id AND x.command_key = p_key;
  IF s.id IS NOT NULL THEN
    -- a replay answers the first survey only to a caller who may still record on that survey's branch (review r1 P1): the same
    -- not-found as for a visit outside the caller's branches, so the replay never confirms a survey the caller cannot see
    IF a.role = 'manager' AND NOT public.app_branch_allowed(s.branch_id) OR a.branch_id IS NOT NULL AND s.branch_id <> a.branch_id THEN
      RAISE EXCEPTION 'ERR_NOT_FOUND: visit not found' USING ERRCODE = 'P0002';
    END IF;
    RETURN s.id;  -- replay of the same key
  END IF;
  SELECT * INTO v FROM public.visits x WHERE x.tenant_id = a.tenant_id AND x.id = (p ->> 'visit_id')::uuid;
  IF v.id IS NULL OR a.role = 'manager' AND NOT public.app_branch_allowed(v.branch_id) OR a.branch_id IS NOT NULL AND v.branch_id <> a.branch_id THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: visit not found' USING ERRCODE = 'P0002';
  END IF;
  IF v.closed_at IS NULL THEN
    RAISE EXCEPTION 'ERR_VERSION_CONFLICT: visit_open' USING ERRCODE = '55000';
  END IF;
  IF EXISTS (SELECT 1 FROM public.surveys x WHERE x.tenant_id = a.tenant_id AND x.visit_id = v.id) THEN
    RAISE EXCEPTION 'ERR_IDEMPOTENCY_CONFLICT: visit_surveyed' USING ERRCODE = '23505';
  END IF;
  v_now := clock_timestamp();
  v_patient := public.patient_canonical(a.tenant_id, v.patient_id);
  v_id := public.uuid_generate_v7();
  IF v_score <= 2 THEN
    -- the visit branch's first active manager (by staff id); unassigned when none (the branch manager still reads and works it)
    SELECT sb.staff_id INTO v_mgr FROM public.staff_branches sb
      JOIN public.staff st ON st.tenant_id = sb.tenant_id AND st.id = sb.staff_id
      JOIN public.memberships m ON m.tenant_id = st.tenant_id AND m.id = st.membership_id
     WHERE sb.tenant_id = a.tenant_id AND sb.branch_id = v.branch_id AND sb.role = 'manager'
       AND m.effective_from <= v_now AND (m.effective_to IS NULL OR m.effective_to > v_now)
     ORDER BY sb.staff_id LIMIT 1;
    PERFORM public.followup_create(a.tenant_id, v.branch_id, v_patient, 'survey_low', 'survey', v_id, 'low', 'cs', v_mgr,
                                   public.followup_branch_today(a.tenant_id, v.branch_id, v_now), v_now);
    SELECT f.id INTO v_fu FROM public.followups f
     WHERE f.tenant_id = a.tenant_id AND f.rule_code = 'survey_low' AND f.source_id = v_id AND f.step = 'low';
  END IF;
  INSERT INTO public.surveys (id, tenant_id, branch_id, visit_id, patient_id, score, review_eligible, followup_id, command_key,
                              recorded_by, recorded_as, recorded_at)
  VALUES (v_id, a.tenant_id, v.branch_id, v.id, v_patient, v_score, v_score >= 4, v_fu, p_key, a.staff_id, a.role, v_now);
  PERFORM public.audit_append('settings_change', 'survey', v_id, 'success', 'survey_recorded');
  RETURN v_id;
END
$$;--> statement-breakpoint
