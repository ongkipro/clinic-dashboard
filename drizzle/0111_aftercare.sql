CREATE FUNCTION public.aftercare_link_lookup(p_token_hash text, p_session_hash text, p_now timestamptz DEFAULT NULL) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  n public.aftercare_notices;
  v_now timestamptz := coalesce(p_now, clock_timestamp());
  v_set jsonb;
  v_meta jsonb;
  v_phone text;
  v_tz text;
  v_state text;
BEGIN
