-- Entries: insert-only; each continues its account's balance (locked) and never goes below 0. A use names a real
-- balance payment of the same branch, amount and canonical patient (BILL-29: never simulated); a charge is never
-- simulated (Release 1 has none that is real, DEC-086).
CREATE FUNCTION public.balance_entries_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  acc public.balance_accounts;
  y public.payments;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('staff_access:' || coalesce(NEW.tenant_id, OLD.tenant_id)::text, 0));
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'balance entries are never changed or deleted' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO acc FROM public.balance_accounts x WHERE x.tenant_id = NEW.tenant_id AND x.id = NEW.account_id FOR UPDATE;
  IF acc.id IS NULL OR NEW.balance_after <> acc.balance + NEW.amount OR NEW.balance_after < 0 THEN
    RAISE EXCEPTION 'an entry continues its account balance and never goes below 0' USING ERRCODE = '42501';
  END IF;
