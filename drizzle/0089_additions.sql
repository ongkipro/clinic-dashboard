-- Tindakan Tambahan of a visit for the cashier (BILL-22): each approved addition with its commercial facts only (item,
-- quantity, branch price now, agreement in force, release with collector, its line and paid amount, performed). No
-- reason, dose or condition; the patient masked for the auditor. Readers: the Kasir readers at the visit's branch.
CREATE FUNCTION public.addition_visit_list(p_visit uuid) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  a record := public.kasir_reader(NULL::uuid);
  v public.visits;
BEGIN
  SELECT * INTO v FROM public.visits x WHERE x.tenant_id = a.tenant_id AND x.id = p_visit;
  IF NOT FOUND OR a.branch_id IS NOT NULL AND v.branch_id <> a.branch_id THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: visit not found' USING ERRCODE = 'P0002';
  END IF;
  RETURN jsonb_build_object('visit_id', v.id, 'branch_id', v.branch_id, 'closed', v.closed_at IS NOT NULL, 'payment', v.payment,
    'patient', public.kasir_patient_json(v.tenant_id, v.patient_id, a.role = 'auditor'),
    'additions', coalesce((SELECT jsonb_agg(jsonb_build_object(
        'plan_item_id', t.id, 'request_id', q.id, 'item_id', cv.item_id, 'name', cv.name, 'quantity', t.qty,
        'price', public.catalog_branch_price(cv.item_id, v.branch_id, clock_timestamp()),
        'consent_active', public.consent_state(t.tenant_id, t.plan_id) = 'active',
        'authorized_by', (SELECT s.display_name FROM public.staff s WHERE s.tenant_id = q.tenant_id AND s.id = q.decided_by),
        'release', (SELECT jsonb_build_object('id', r.id, 'released_at', r.released_at,
                      'released_by', (SELECT s.display_name FROM public.staff s WHERE s.tenant_id = r.tenant_id AND s.id = r.released_by),
                      'collector', (SELECT s.display_name FROM public.staff s WHERE s.tenant_id = r.tenant_id AND s.id = r.collector_staff_id))
                      FROM public.addition_releases r WHERE r.tenant_id = t.tenant_id AND r.plan_item_id = t.id),
        'invoice_line_id', (public.addition_line(v.tenant_id, v.id, t.id)).id,
        'invoice_id', (public.addition_line(v.tenant_id, v.id, t.id)).invoice_id,
        'paid', public.addition_paid(v.tenant_id, v.id, t.id),
        'counted', EXISTS (SELECT 1 FROM public.treatment_executions e WHERE e.tenant_id = t.tenant_id AND e.visit_id = v.id AND e.plan_item_id = t.id
                             AND e.state = 'finished' AND e.counted)) ORDER BY q.decided_at, t.id)
      FROM public.clinical_requests q
      JOIN public.plan_items t ON t.tenant_id = q.tenant_id AND t.id = q.added_item_id
      JOIN public.catalog_versions cv ON cv.tenant_id = t.tenant_id AND cv.id = t.catalog_version_id
     WHERE q.tenant_id = v.tenant_id AND q.visit_id = v.id AND public.addition_of_visit(v.tenant_id, v.id, t.id)), '[]'::jsonb));
END
$$;--> statement-breakpoint
