     WHERE tenant_id = o.tenant_id AND visit_id = o.source_id;
    v_clinic := coalesce(nullif(btrim(public.followup_setting(o.tenant_id, 'SET-1', clock_timestamp()) ->> 'nama'), ''),
                         (SELECT t.legal_name FROM public.tenants t WHERE t.id = o.tenant_id));
    -- "perawatan Anda": the patient's name, the clinic and branch, the path — never a treatment (PRIV-15)
    RETURN ARRAY[v_name, v_clinic || ' – ' || v_branch, '/aftercare/' || v_token];
  END IF;
  RETURN ARRAY[v_branch];
END
