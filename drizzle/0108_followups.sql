-- T-093 DRAFT: readers and the writer (plan r1 P2-1, P2-2 (2); r2 P3-1). Not in any worktree.

-- The writer (P2-2 (2)): done (outcome, note for lainnya) | dismiss (dilewati, note) | snooze (a later branch date) | assign | unassign.
-- p: {action, outcome?, note?, due_on?, staff_id?}; exactly that key set. Writers: central_cs (tenant), manager (branch), bc (bc queue, own).
CREATE FUNCTION public.followup_update(p_followup uuid, p jsonb) RETURNS text
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  a record;
  f public.followups;
  v_action text := p ->> 'action';
  v_now timestamptz;
  v_today date;
  v_note text := NULLIF(btrim(coalesce(p ->> 'note', '')), '');
BEGIN
  SELECT x.tenant_id, x.staff_id, x.role, x.branch_id INTO a FROM public.tenant_actor_lock() x;
  IF a.role NOT IN ('central_cs','manager','bc') THEN
    RAISE EXCEPTION 'ERR_FORBIDDEN: role may not work follow-ups' USING ERRCODE = '42501';
  END IF;
  IF NOT public.tenant_capability('existing_appointment') THEN
    RAISE EXCEPTION 'ERR_TENANT_SUSPENDED: the tenant cannot change follow-ups now' USING ERRCODE = '42501';
  END IF;
  IF jsonb_typeof(p) IS DISTINCT FROM 'object' OR coalesce(v_action, '') NOT IN ('done','dismiss','snooze','assign','unassign')
     OR p - 'action' - 'outcome' - 'note' - 'due_on' - 'staff_id' <> '{}'::jsonb THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: followup' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO f FROM public.followups x WHERE x.tenant_id = a.tenant_id AND x.id = p_followup FOR UPDATE;
  IF f.id IS NULL OR NOT public.followups_readable(f.tenant_id, f.branch_id, f.rule_code, f.role_queue, f.assignee_staff_id)
     OR a.branch_id IS NOT NULL AND f.branch_id <> a.branch_id OR a.role = 'bc' AND f.role_queue <> 'bc' THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: follow-up not found' USING ERRCODE = 'P0002';
  END IF;
  IF f.state <> 'open' THEN
    RAISE EXCEPTION 'ERR_VERSION_CONFLICT: followup_closed' USING ERRCODE = '55000';
  END IF;
  v_now := clock_timestamp();
  v_today := public.followup_branch_today(f.tenant_id, f.branch_id, v_now);
  BEGIN
    IF v_action = 'done' THEN
      IF coalesce(p ->> 'outcome', '') NOT IN ('dihubungi','jadwal_dibuat','sudah_bayar','tidak_tertarik','tidak_merespons','lainnya')
         OR p ->> 'outcome' = 'lainnya' AND length(coalesce(v_note, '')) < 3 THEN
        RAISE EXCEPTION 'ERR_INVALID_INPUT: outcome' USING ERRCODE = '22023';
      END IF;
      UPDATE public.followups SET state = 'done', outcome = p ->> 'outcome', outcome_note = v_note, closed_by = a.staff_id, closed_as = a.role,
             closed_at = v_now, updated_at = v_now WHERE tenant_id = f.tenant_id AND id = f.id RETURNING * INTO f;
    ELSIF v_action = 'dismiss' THEN
      IF length(coalesce(v_note, '')) < 3 THEN
        RAISE EXCEPTION 'ERR_INVALID_INPUT: note' USING ERRCODE = '22023';
      END IF;
      UPDATE public.followups SET state = 'dismissed', outcome = 'dilewati', outcome_note = v_note, closed_by = a.staff_id, closed_as = a.role,
             closed_at = v_now, updated_at = v_now WHERE tenant_id = f.tenant_id AND id = f.id RETURNING * INTO f;
    ELSIF v_action = 'snooze' THEN
      IF (p ->> 'due_on')::date <= greatest(v_today, f.due_on) OR (p ->> 'due_on')::date > v_today + 90 THEN
        RAISE EXCEPTION 'ERR_INVALID_INPUT: due_on' USING ERRCODE = '22023';
      END IF;
      UPDATE public.followups SET due_on = (p ->> 'due_on')::date, snooze_count = snooze_count + 1, updated_at = v_now
       WHERE tenant_id = f.tenant_id AND id = f.id RETURNING * INTO f;
    ELSIF v_action = 'assign' THEN
      IF a.role = 'bc' AND (p ->> 'staff_id')::uuid IS DISTINCT FROM a.staff_id THEN
        RAISE EXCEPTION 'ERR_FORBIDDEN: a BC takes follow-ups for itself' USING ERRCODE = '42501';
      END IF;
      -- an active member who works this queue: cs → central_cs (tenant-wide) or a manager of the branch; bc → a bc of the branch
      IF NOT EXISTS (SELECT 1 FROM public.staff st JOIN public.memberships m ON m.tenant_id = st.tenant_id AND m.id = st.membership_id
                      WHERE st.tenant_id = f.tenant_id AND st.id = (p ->> 'staff_id')::uuid AND m.effective_from <= v_now
                        AND (m.effective_to IS NULL OR m.effective_to > v_now)
                        AND (f.role_queue = 'cs' AND (EXISTS (SELECT 1 FROM public.staff_roles r WHERE r.tenant_id = st.tenant_id AND r.staff_id = st.id AND r.role = 'central_cs')
                                                      OR EXISTS (SELECT 1 FROM public.staff_branches sb WHERE sb.tenant_id = st.tenant_id AND sb.staff_id = st.id
                                                                   AND sb.role = 'manager' AND sb.branch_id = f.branch_id))
                          OR f.role_queue = 'bc' AND EXISTS (SELECT 1 FROM public.staff_branches sb WHERE sb.tenant_id = st.tenant_id AND sb.staff_id = st.id
                                                               AND sb.role = 'bc' AND sb.branch_id = f.branch_id))) THEN
        RAISE EXCEPTION 'ERR_NOT_FOUND: staff not found' USING ERRCODE = 'P0002';
      END IF;
      UPDATE public.followups SET assignee_staff_id = (p ->> 'staff_id')::uuid, assigned_at = v_now, updated_at = v_now
       WHERE tenant_id = f.tenant_id AND id = f.id RETURNING * INTO f;
    ELSE
      UPDATE public.followups SET assignee_staff_id = NULL, assigned_at = NULL, updated_at = v_now
       WHERE tenant_id = f.tenant_id AND id = f.id RETURNING * INTO f;
    END IF;
  EXCEPTION WHEN invalid_text_representation OR invalid_datetime_format OR datetime_field_overflow THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: followup' USING ERRCODE = '22023';
  END;
  PERFORM public.audit_append('settings_change', 'followup', f.id, 'success', 'followup_' || v_action);
  IF v_action IN ('done','dismiss') THEN
    INSERT INTO public.domain_events (tenant_id, branch_id, type, aggregate_kind, aggregate_id, staff_id, acting_role, occurred_at, payload)
    VALUES (f.tenant_id, f.branch_id, 'FollowUpClosed', 'followup', f.id, a.staff_id, a.role, v_now,
            jsonb_build_object('followup_id', f.id, 'patient_id', f.patient_id, 'rule_code', f.rule_code, 'outcome', f.outcome));
  END IF;
  RETURN f.state;
END
$$;--> statement-breakpoint
REVOKE ALL ON FUNCTION public.followup_update(uuid, jsonb) FROM PUBLIC;--> statement-breakpoint
