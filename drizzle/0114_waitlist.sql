CREATE FUNCTION public.appointments_waitlist_offer() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  v_item uuid;
  w public.waitlist_entries;
  v_now timestamptz := clock_timestamp();
BEGIN
