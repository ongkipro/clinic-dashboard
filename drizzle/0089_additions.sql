-- The second alert (PR-15, PR-54; plan open point 2): when an addition of the visit finishes counted and is not paid
-- in full in real money, FO/cashier and the manager of the branch are alerted (one per execution, subject the plan
-- item; no clinical text), and the visit's payment step is recomputed (a performed addition not billed owes). Runs in
-- treatment_finish's transaction, which already holds staff_access and the visit lock (plan r2).
CREATE FUNCTION public.addition_finished() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  v_event uuid;
BEGIN
  IF OLD.state = 'finished' OR NEW.state <> 'finished' OR NOT NEW.counted OR NOT public.addition_of_visit(NEW.tenant_id, NEW.visit_id, NEW.plan_item_id) THEN
    RETURN NULL;
  END IF;
  IF NOT public.addition_paid(NEW.tenant_id, NEW.visit_id, NEW.plan_item_id) THEN
    INSERT INTO public.domain_events (tenant_id, branch_id, type, aggregate_kind, aggregate_id, staff_id, acting_role, payload)
    VALUES (NEW.tenant_id, NEW.branch_id, 'AdditionFinishedUnpaid', 'treatment_execution', NEW.id, NEW.finished_by, NEW.finished_as,
