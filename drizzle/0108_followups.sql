    'rule_code', f.rule_code, 'source_kind', f.source_kind, 'source_id', CASE WHEN v.identity THEN f.source_id END, 'step', f.step,
    'role_queue', f.role_queue, 'assignee_staff_id', f.assignee_staff_id,
    'assignee_name', (SELECT s.display_name FROM public.staff s WHERE s.tenant_id = f.tenant_id AND s.id = f.assignee_staff_id),
    'patient_id', CASE WHEN v.identity OR p_role = 'auditor' THEN f.patient_id END,
    'patient_name', CASE WHEN v.identity THEN (SELECT pt.full_name FROM public.patients pt WHERE pt.tenant_id = f.tenant_id AND pt.id = f.patient_id) END,
    'patient_mrn', CASE WHEN v.identity THEN (SELECT pt.mrn FROM public.patients pt WHERE pt.tenant_id = f.tenant_id AND pt.id = f.patient_id)
                        WHEN p_role = 'auditor' THEN (SELECT '***' || right(pt.mrn, 3) FROM public.patients pt WHERE pt.tenant_id = f.tenant_id AND pt.id = f.patient_id) END,
    'consent_masked', NOT v.identity, 'promo_blocked', f.rule_code = 'dormant' AND NOT v.consent,
    'original_due_on', f.original_due_on, 'due_on', f.due_on, 'snooze_count', f.snooze_count,
    'due_today', f.state = 'open' AND f.due_on = p_today, 'overdue', f.state = 'open' AND f.due_on < p_today,
    'state', f.state, 'outcome', f.outcome,
    'outcome_note', CASE WHEN p_role IN ('owner','central_cs','manager','bc','finance') THEN f.outcome_note END,
    'closed_at', f.closed_at, 'created_at', f.created_at)
  FROM v
$$;--> statement-breakpoint
