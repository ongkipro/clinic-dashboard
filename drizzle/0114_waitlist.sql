       WHERE tenant_id = w.tenant_id AND id = w.id;
      INSERT INTO public.notifications (tenant_id, type, recipient_role, branch_id, subject_kind, subject_id)
      SELECT NEW.tenant_id, 'waitlist_offer', r, NEW.branch_id, 'waitlist_entry', w.id FROM unnest(ARRAY['fo_cashier','central_cs','manager']) r;
      INSERT INTO public.domain_events (tenant_id, branch_id, type, aggregate_kind, aggregate_id, staff_id, acting_role, occurred_at, payload)
      VALUES (NEW.tenant_id, NEW.branch_id, 'WaitlistOffered', 'waitlist_entry', w.id, NULL, NULL, v_now,
              jsonb_build_object('waitlist_entry_id', w.id, 'appointment_id', NEW.id, 'branch_id', NEW.branch_id, 'patient_id', w.patient_id));
