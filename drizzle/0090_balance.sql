       SELECT 1 FROM public.payment_charges c JOIN public.invoices i ON i.tenant_id = c.tenant_id AND i.id = c.invoice_id
        WHERE c.tenant_id = NEW.tenant_id AND c.id = NEW.charge_id AND NOT c.is_simulated
          AND public.patient_canonical(i.tenant_id, i.patient_id) = acc.patient_id) THEN
    RAISE EXCEPTION 'simulated money never reaches a balance' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END
