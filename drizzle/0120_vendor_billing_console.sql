BEGIN
  SELECT * INTO w FROM public.vendor_console_writer(p_token, p_ip, v_roles, v_action,
                                                    (SELECT r.tenant_id FROM public.vendor_requests r WHERE r.id = p_request));
  IF w.refusal IS NOT NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'ERR_FORBIDDEN', 'reason', w.refusal);
  END IF;
  SELECT * INTO q FROM public.vendor_requests WHERE id = p_request FOR UPDATE;
  IF q.id IS NULL OR q.kind NOT IN ('server_fee_change','invoice_waiver') THEN
    PERFORM public.vendor_log(w.staff_id, w.account_id, w.role, v_action, q.tenant_id, p_request, 'denied', 'not_found', p_ip);
    PERFORM public.vendor_authority_recheck(p_token, p_ip, v_roles, interval '10 minutes');
    RETURN jsonb_build_object('ok', false, 'code', 'ERR_NOT_FOUND');
  END IF;
  IF q.requested_by = w.staff_id THEN
    PERFORM public.vendor_log(w.staff_id, w.account_id, w.role, v_action, q.tenant_id, p_request, 'denied', 'approver_is_requester', p_ip);
    PERFORM public.vendor_authority_recheck(p_token, p_ip, v_roles, interval '10 minutes');
