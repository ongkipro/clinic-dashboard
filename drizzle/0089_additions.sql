    v_item := NULLIF(p ->> 'plan_item_id', '')::uuid;
    v_performer := NULLIF(p ->> 'performer_id', '')::uuid;
    v_assistant := NULLIF(p ->> 'assistant_id', '')::uuid;
    v_supervisor := NULLIF(p ->> 'supervisor_id', '')::uuid;
    v_room := NULLIF(p ->> 'room_id', '')::uuid;
