-- A visit that closes with aftercare: the notice, then the care message (no marketing consent: PR-70; a suspended tenant's care continues:
-- PR-56). A refusal to queue (no phone, no sendable number, no approved perawatan_anda) leaves the notice without a message — never an
-- error into visit close. visit_close is not re-created (the 0091 package_visit_closed pattern).
CREATE FUNCTION public.visit_aftercare() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  v_versions uuid[];
  v_tpl uuid;
  v_tz text;
  v_out uuid;
BEGIN
  IF OLD.closed_at IS NOT NULL OR NEW.closed_at IS NULL THEN
    RETURN NULL;
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('staff_access:' || NEW.tenant_id::text, 0));
  v_versions := public.aftercare_versions(NEW.tenant_id, NEW.id);
  IF cardinality(v_versions) = 0 THEN
    RETURN NULL;
  END IF;
  SELECT t.id INTO v_tpl FROM public.wa_templates t
   WHERE t.tenant_id = NEW.tenant_id AND t.name = 'perawatan_anda' AND t.status = 'approved' AND t.category = 'utility'
   ORDER BY t.language = 'id' DESC, t.id LIMIT 1;
  SELECT b.timezone INTO v_tz FROM public.branches b WHERE b.tenant_id = NEW.tenant_id AND b.id = NEW.branch_id;
  -- review r2 P3-2: queue first, then the notice carries the queued row (NULL when refused or without a template)
  IF v_tpl IS NOT NULL THEN
    BEGIN
      v_out := public.outbound_enqueue_do(NEW.tenant_id, 'aftercare:' || NEW.id::text, 'aftercare', NEW.patient_id, NEW.branch_id, v_tpl,
                                          'visit', NEW.id, (NEW.closed_at AT TIME ZONE coalesce(v_tz, 'Asia/Jakarta'))::date, NULL, NULL, NEW.closed_at);
    EXCEPTION WHEN SQLSTATE '55000' OR SQLSTATE 'P0002' OR SQLSTATE '22023' THEN
      v_out := NULL;
    END;
  END IF;
  INSERT INTO public.aftercare_notices (tenant_id, branch_id, visit_id, patient_id, catalog_version_ids, outbound_id, created_at)
  VALUES (NEW.tenant_id, NEW.branch_id, NEW.id, public.patient_canonical(NEW.tenant_id, NEW.patient_id), v_versions, v_out, NEW.closed_at)
  ON CONFLICT (tenant_id, visit_id) DO NOTHING;
  RETURN NULL;
END
$$;--> statement-breakpoint
