-- Guard: the staff_access lock first; never deleted; inserted open; identity, original_due_on and the source frozen; nothing changes once
-- closed; due_on only moves forward (Tunda).
CREATE FUNCTION public.followups_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('staff_access:' || coalesce(NEW.tenant_id, OLD.tenant_id)::text, 0));
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'follow-ups are never deleted' USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.state <> 'open' OR NEW.due_on <> NEW.original_due_on THEN
      RAISE EXCEPTION 'a follow-up starts open on its due date' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
  END IF;
  IF (NEW.id, NEW.tenant_id, NEW.branch_id, NEW.patient_id, NEW.rule_code, NEW.source_kind, NEW.source_id, NEW.step, NEW.role_queue,
      NEW.original_due_on, NEW.created_at)
     IS DISTINCT FROM (OLD.id, OLD.tenant_id, OLD.branch_id, OLD.patient_id, OLD.rule_code, OLD.source_kind, OLD.source_id, OLD.step, OLD.role_queue,
      OLD.original_due_on, OLD.created_at)
     OR OLD.state <> 'open'
     OR NEW.due_on < OLD.due_on
     OR NEW.snooze_count < OLD.snooze_count THEN
    RAISE EXCEPTION 'a follow-up keeps its rule and source; a closed one is final' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END
$$;--> statement-breakpoint
