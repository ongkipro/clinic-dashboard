CREATE FUNCTION public.waitlist_add(p_key text, p jsonb) RETURNS uuid
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  a record := public.waitlist_actor(ARRAY['owner','admin_pusat','manager','fo_cashier','central_cs']);
  w public.waitlist_entries;
  v_patient uuid;
  v_id uuid;
BEGIN
  IF NOT public.tenant_capability('new_booking') THEN
    RAISE EXCEPTION 'ERR_TENANT_SUSPENDED' USING ERRCODE = '42501';
  END IF;
  IF jsonb_typeof(p) IS DISTINCT FROM 'object' OR p - 'branch_id' - 'patient_id' - 'item_id' <> '{}'::jsonb
     OR coalesce(p_key, '') !~ '^[A-Za-z0-9_.:-]{8,128}$'
     OR jsonb_typeof(p -> 'branch_id') IS DISTINCT FROM 'string' OR jsonb_typeof(p -> 'patient_id') IS DISTINCT FROM 'string'
     OR jsonb_typeof(p -> 'item_id') IS DISTINCT FROM 'string'
     OR (p ->> 'branch_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
     OR (p ->> 'patient_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
     OR (p ->> 'item_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: waitlist' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO w FROM public.waitlist_entries x WHERE x.tenant_id = a.tenant_id AND x.command_key = p_key;
  IF w.id IS NOT NULL THEN
    PERFORM public.waitlist_entry_for(a, w.id); -- a replay answers only an actor who may still see that entry's branch
    RETURN w.id;
  END IF;
  PERFORM public.booking_branch(a.tenant_id, a.staff_id, a.role, (p ->> 'branch_id')::uuid);
  IF a.branch_id IS NOT NULL AND (p ->> 'branch_id')::uuid <> a.branch_id THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: branch not found' USING ERRCODE = 'P0002';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.patients pt WHERE pt.tenant_id = a.tenant_id AND pt.id = (p ->> 'patient_id')::uuid) THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: patient not found' USING ERRCODE = 'P0002';
  END IF;
  -- a service the branch offers
  IF NOT EXISTS (SELECT 1 FROM public.catalog_items i JOIN public.branch_services bs ON bs.tenant_id = i.tenant_id AND bs.item_id = i.id
                  WHERE i.tenant_id = a.tenant_id AND i.id = (p ->> 'item_id')::uuid AND i.kind = 'service' AND bs.branch_id = (p ->> 'branch_id')::uuid) THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: service not offered at this branch' USING ERRCODE = 'P0002';
  END IF;
  v_patient := public.patient_canonical(a.tenant_id, (p ->> 'patient_id')::uuid);
  -- review r1 P1: entries keep the patient id they were added with (identity frozen); after a merge the open entry of a merged record
  -- belongs to the survivor, so the check covers the canonical patient's whole cluster.
  IF EXISTS (SELECT 1 FROM public.waitlist_entries x WHERE x.tenant_id = a.tenant_id AND x.patient_id = ANY (public.patient_cluster(a.tenant_id, v_patient))
              AND x.branch_id = (p ->> 'branch_id')::uuid AND x.item_id = (p ->> 'item_id')::uuid AND x.state IN ('waiting','offered')) THEN
    RAISE EXCEPTION 'ERR_IDEMPOTENCY_CONFLICT: already_waiting' USING ERRCODE = '23505';
  END IF;
  INSERT INTO public.waitlist_entries (tenant_id, branch_id, patient_id, item_id, command_key, created_by, created_as)
  VALUES (a.tenant_id, (p ->> 'branch_id')::uuid, v_patient, (p ->> 'item_id')::uuid, p_key, a.staff_id, a.role) RETURNING id INTO v_id;
  PERFORM public.audit_append('settings_change', 'waitlist_entry', v_id, 'success', 'waitlist_added');
