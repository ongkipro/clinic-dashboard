-- kasir_visit_payment (re-created from 0087): in progress while an issued invoice owes or a performed addition is
-- not billed (PR-7, PR-15, CLIN-020; plan r1 P1-2), checked before not_started.
CREATE OR REPLACE FUNCTION public.kasir_visit_payment(p_tenant uuid, p_visit uuid) RETURNS void
LANGUAGE plpgsql VOLATILE SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  v_state text;
BEGIN
  IF p_visit IS NULL THEN
    RETURN;
  END IF;
  v_state := CASE
    WHEN EXISTS (SELECT 1 FROM public.invoices i WHERE i.tenant_id = p_tenant AND i.visit_id = p_visit AND i.state = 'issued'
                   AND public.kasir_outstanding(i.tenant_id, i.id) > 0)
      OR public.addition_unbilled_counted(p_tenant, p_visit) THEN 'in_progress'
    WHEN NOT EXISTS (SELECT 1 FROM public.invoices i WHERE i.tenant_id = p_tenant AND i.visit_id = p_visit AND i.state = 'issued') THEN 'not_started'
    ELSE 'done' END;
  UPDATE public.visits SET payment = v_state WHERE tenant_id = p_tenant AND id = p_visit AND closed_at IS NULL AND payment IS DISTINCT FROM v_state;
END
