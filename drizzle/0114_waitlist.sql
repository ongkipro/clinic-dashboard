-- Never deleted; created waiting; identity frozen; transitions: waiting→offered (the trigger), offered→waiting (declined),
-- offered→booked, waiting|offered→removed. The staff_access lock first (DEC-043).
CREATE FUNCTION public.waitlist_entries_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('staff_access:' || coalesce(NEW.tenant_id, OLD.tenant_id)::text, 0));
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'a waitlist entry is never deleted' USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.state <> 'waiting' OR NEW.offered_appointment_id IS NOT NULL OR NEW.closed_at IS NOT NULL THEN
      RAISE EXCEPTION 'a waitlist entry starts waiting' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
  END IF;
  IF (NEW.id, NEW.tenant_id, NEW.branch_id, NEW.patient_id, NEW.item_id, NEW.command_key, NEW.created_by, NEW.created_as, NEW.created_at)
     IS DISTINCT FROM (OLD.id, OLD.tenant_id, OLD.branch_id, OLD.patient_id, OLD.item_id, OLD.command_key, OLD.created_by, OLD.created_as, OLD.created_at)
     OR NOT ((OLD.state, NEW.state) IN (('waiting','offered'), ('offered','waiting'), ('offered','booked'), ('waiting','removed'), ('offered','removed'))) THEN
    RAISE EXCEPTION 'a waitlist entry keeps its identity and moves only along its states' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END
