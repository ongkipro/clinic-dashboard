-- T-091 rules (generated by gen.py; plan docs/tasks/T-091.md)
-- ── T-091 (PR-43 inbox flag; effective R3; plan Argon 4a4563fd REVISE adopted, 2963d957): a complaint flagged from an inbound WhatsApp message.
-- complaint_flag_do holds the shared rules (triage/category validation, the manager and pharmacist rules, insert, event, audit, notifications);
-- complaint_flag (0074) is re-created to delegate to it and keeps every behaviour incl. the refusal of source 'message'; complaint_guard freezes
-- message_id; complaint_json projects it. No message body is copied (W-10). ──

-- The shared body (not granted). a: the complaint actor; the caller resolved patient (canonical), branch and visit / message.
CREATE FUNCTION public.complaint_flag_do(a record, p_patient uuid, p_branch uuid, p_visit uuid, p_message uuid, p_source text, p jsonb) RETURNS uuid
LANGUAGE plpgsql VOLATILE SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  v_kind text := p ->> 'kind';
  v_triage text;
  v_id uuid;
  v_now timestamptz;
  v_event uuid;
  r text;
BEGIN
  IF jsonb_typeof(p) IS DISTINCT FROM 'object' OR p - 'kind' - 'summary' - 'triage' - 'category' <> '{}'::jsonb
     OR coalesce(v_kind, '') NOT IN ('klinis','layanan')
     OR jsonb_typeof(p -> 'summary') IS DISTINCT FROM 'string' OR length(btrim(p ->> 'summary')) NOT BETWEEN 3 AND 1000
     OR v_kind = 'klinis' AND (p ? 'category' OR p ? 'triage' AND coalesce(p ->> 'triage', '') NOT IN ('merah','kuning','hijau'))
     OR v_kind = 'layanan' AND (p ? 'triage' OR coalesce(p ->> 'category', '') NOT IN ('waktu_tunggu','tagihan','sikap_staf','lainnya')) THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: complaint' USING ERRCODE = '22023';
  END IF;
  IF a.role = 'manager' AND v_kind <> 'layanan' OR p_source = 'pharmacist' AND (a.role <> 'pharmacist' OR v_kind <> 'klinis') THEN
    RAISE EXCEPTION 'ERR_FORBIDDEN: role may not raise this complaint' USING ERRCODE = '42501';
  END IF;
  v_now := clock_timestamp();
  v_triage := CASE WHEN v_kind = 'klinis' THEN coalesce(p ->> 'triage', 'kuning') END;
  INSERT INTO public.complaint_tasks (tenant_id, branch_id, patient_id, visit_id, message_id, kind, source, triage, category, summary, due_at,
                                      flagged_by, flagged_as, created_at)
  VALUES (a.tenant_id, p_branch, p_patient, p_visit, p_message, v_kind, p_source, v_triage, p ->> 'category', btrim(p ->> 'summary'),
          public.complaint_due_at(a.tenant_id, p_branch, v_kind, v_triage, v_now), a.staff_id, a.role, v_now)
  RETURNING id INTO v_id;
  INSERT INTO public.complaint_events (tenant_id, branch_id, task_id, task_kind, kind, actor_id, actor_role) VALUES (a.tenant_id, p_branch, v_id, v_kind, 'flagged', a.staff_id, a.role);
  PERFORM public.audit_append('settings_change', 'complaint_task', v_id, 'success', 'complaint_flagged');
  INSERT INTO public.domain_events (branch_id, type, aggregate_kind, aggregate_id, payload)
  VALUES (p_branch, 'ComplaintFlagged', 'complaint_task', v_id,
          jsonb_strip_nulls(jsonb_build_object('task_id', v_id, 'branch_id', p_branch, 'patient_id', p_patient, 'visit_id', p_visit, 'message_id', p_message,
                                               'kind', v_kind, 'source', p_source, 'triage', v_triage, 'category', p ->> 'category')))
  RETURNING id INTO v_event;
  FOREACH r IN ARRAY CASE v_kind WHEN 'klinis' THEN ARRAY['doctor','nurse','pharmacist','facility_head'] ELSE ARRAY['manager','facility_head'] END LOOP
    INSERT INTO public.notifications (tenant_id, type, recipient_role, branch_id, subject_kind, subject_id, source_event_id, raised_by)
    VALUES (a.tenant_id, 'complaint_' || v_kind, r, p_branch, 'complaint_task', v_id, v_event, a.staff_id);
  END LOOP;
  RETURN v_id;
END
$$;--> statement-breakpoint
