-- Target & Scorecard Staf: the owner (tenant-wide, or a branch's assigned staff) and a manager (its active allowed branch). One row per staff
-- member assigned there (or every staff member with a branch role / a BC role, tenant-wide).
CREATE FUNCTION public.target_list(p_period text DEFAULT NULL, p_branch uuid DEFAULT NULL) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  a record;
  w record;
  v_branch uuid := p_branch;
BEGIN
  SELECT x.tenant_id, x.staff_id, x.role, x.branch_id INTO a FROM public.tenant_actor_lock() x;
  IF a.role NOT IN ('owner','manager') THEN
    RAISE EXCEPTION 'ERR_FORBIDDEN: role may not list staff targets' USING ERRCODE = '42501';
  END IF;
  IF a.role = 'manager' THEN
    v_branch := coalesce(p_branch, a.branch_id);
    IF v_branch IS NULL OR NOT public.app_branch_allowed(v_branch) THEN
      RAISE EXCEPTION 'ERR_FORBIDDEN: not your branch' USING ERRCODE = '42501';
    END IF;
  END IF;
  IF v_branch IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.branches b WHERE b.tenant_id = a.tenant_id AND b.id = v_branch) THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: branch not found' USING ERRCODE = 'P0002';
  END IF;
  w := public.target_period(p_period);
  RETURN jsonb_build_object('role', a.role, 'period', w.period_key, 'period_kind', w.period_kind, 'branch_id', v_branch, 'can_set', a.role = 'owner',
    'rows', coalesce((SELECT jsonb_agg(public.target_row(a.tenant_id, st.id, w.period_key, w.period_start, w.period_end, v_branch) ORDER BY st.display_name, st.id)
                        FROM public.staff st
                       WHERE st.tenant_id = a.tenant_id
                         AND EXISTS (SELECT 1 FROM public.staff_roles r WHERE r.tenant_id = st.tenant_id AND r.staff_id = st.id AND r.role = ANY (public.target_own_roles()))
                         AND (v_branch IS NULL OR EXISTS (SELECT 1 FROM public.staff_branches sb WHERE sb.tenant_id = st.tenant_id AND sb.staff_id = st.id AND sb.branch_id = v_branch))), '[]'::jsonb));
END
$$;--> statement-breakpoint
REVOKE ALL ON FUNCTION public.target_list(text, uuid) FROM PUBLIC;--> statement-breakpoint
GRANT EXECUTE ON FUNCTION public.target_list(text, uuid) TO clinic_app;
