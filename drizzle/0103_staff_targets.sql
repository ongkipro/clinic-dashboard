-- A period key's kind and window [start, end) in Asia/Jakarta (SET-25: bulanan YYYY-MM, triwulan YYYY-Qn); NULL key → SET-25's periode
-- and the current WIB month or quarter.
CREATE FUNCTION public.target_period(p_period text, OUT period_kind text, OUT period_key text, OUT period_start timestamptz, OUT period_end timestamptz)
LANGUAGE plpgsql STABLE SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  v_today date := (clock_timestamp() AT TIME ZONE 'Asia/Jakarta')::date;
  m date;
BEGIN
  IF p_period IS NULL THEN
    IF coalesce(public.setting_value_at('SET-25', NULL, clock_timestamp()) ->> 'periode', 'bulanan') = 'triwulan' THEN
      p_period := to_char(v_today, 'YYYY') || '-Q' || to_char(v_today, 'Q');
    ELSE
      p_period := to_char(v_today, 'YYYY-MM');
    END IF;
  END IF;
  IF p_period ~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    period_kind := 'bulanan';
    m := to_date(p_period || '-01', 'YYYY-MM-DD');
    period_start := m::timestamp AT TIME ZONE 'Asia/Jakarta';
    period_end := (m + interval '1 month')::timestamp AT TIME ZONE 'Asia/Jakarta';
  ELSIF p_period ~ '^\d{4}-Q[1-4]$' THEN
    period_kind := 'triwulan';
    m := make_date(substr(p_period, 1, 4)::int, (substr(p_period, 7, 1)::int - 1) * 3 + 1, 1);
    period_start := m::timestamp AT TIME ZONE 'Asia/Jakarta';
    period_end := (m + interval '3 months')::timestamp AT TIME ZONE 'Asia/Jakarta';
  ELSE
    RAISE EXCEPTION 'ERR_INVALID_INPUT: period' USING ERRCODE = '22023';
  END IF;
  period_key := p_period;
END
