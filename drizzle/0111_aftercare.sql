CREATE FUNCTION public.aftercare_otp_send(p_token_hash text, p_otp_hash text, p_ip_hash text, p_now timestamptz DEFAULT NULL) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  n public.aftercare_notices;
  o public.outbound_messages;
  t public.wa_templates;
  v_now timestamptz := coalesce(p_now, clock_timestamp());
  v_reason text;
BEGIN
  IF public.app_tenant_id() IS NOT NULL THEN
    RAISE EXCEPTION 'ERR_FORBIDDEN: the aftercare page is unbound' USING ERRCODE = '42501';
  END IF;
  IF p_otp_hash IS NULL OR p_otp_hash !~ '^[0-9a-f]{64}$' OR p_ip_hash IS NULL OR p_ip_hash !~ '^[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: otp' USING ERRCODE = '22023';
  END IF;
  n := public.aftercare_notice_of(p_token_hash);
  IF n.id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'not_found');
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('staff_access:' || n.tenant_id::text, 0));
  SELECT * INTO n FROM public.aftercare_notices x WHERE x.tenant_id = n.tenant_id AND x.id = n.id FOR UPDATE;
  SELECT * INTO o FROM public.outbound_messages x WHERE x.tenant_id = n.tenant_id AND x.id = n.outbound_id;
  SELECT * INTO t FROM public.wa_templates x
   WHERE x.tenant_id = n.tenant_id AND x.waba_id = o.waba_id AND x.name = 'kode_otp' AND x.status = 'approved' AND x.category = 'authentication'
   ORDER BY x.language = 'id' DESC, x.id LIMIT 1;
  v_reason := CASE
    WHEN n.expires_at <= v_now THEN 'link_expired'
    WHEN n.otp_locked_until > v_now THEN 'otp_locked'
    WHEN (SELECT count(*) FROM public.aftercare_otp_sends s WHERE s.tenant_id = n.tenant_id AND s.phone = o.contact_wa_id AND s.outcome = 'sent'
            AND s.sent_at > v_now - interval '10 minutes') >= 3
      OR (SELECT count(*) FROM public.aftercare_otp_sends s WHERE s.ip_hash = p_ip_hash AND s.outcome = 'sent' AND s.sent_at > v_now - interval '1 minute') >= 10
      THEN 'rate_limited'
    WHEN t.id IS NULL OR NOT public.inbox_can_send(n.tenant_id, o.waba_id, o.wa_number_id) THEN 'number_not_sending'
  END;
  INSERT INTO public.aftercare_otp_sends (tenant_id, notice_id, phone, ip_hash, outcome, sent_at)
  VALUES (n.tenant_id, n.id, o.contact_wa_id, p_ip_hash, coalesce(v_reason, 'sent'), v_now);
  IF v_reason IS NOT NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', v_reason);
  END IF;
  UPDATE public.aftercare_notices SET otp_hash = p_otp_hash, otp_expires_at = v_now + interval '5 minutes', otp_attempts = 0
   WHERE tenant_id = n.tenant_id AND id = n.id;
  RETURN jsonb_build_object('ok', true,
    'meta_waba_id', (SELECT w.meta_waba_id FROM public.waba_accounts w WHERE w.tenant_id = n.tenant_id AND w.id = o.waba_id),
    'phone_number_id', (SELECT x.phone_number_id FROM public.wa_numbers x WHERE x.tenant_id = n.tenant_id AND x.id = o.wa_number_id),
    'to', o.contact_wa_id, 'template_name', t.name, 'template_language', t.language, 'tenant_id', n.tenant_id,
    'encrypted_token', (SELECT v.encrypted_token FROM public.token_vault v WHERE v.tenant_id = n.tenant_id AND v.waba_id = o.waba_id AND v.revoked_at IS NULL),
    'keys', (SELECT coalesce(jsonb_agg(jsonb_build_object('version', k.version, 'wrapped', k.wrapped, 'is_current', k.is_current) ORDER BY k.version), '[]'::jsonb)
               FROM public.tenant_data_keys k WHERE k.tenant_id = n.tenant_id));
END
$$;--> statement-breakpoint
REVOKE ALL ON FUNCTION public.aftercare_otp_send(text, text, text, timestamptz) FROM PUBLIC;--> statement-breakpoint
GRANT EXECUTE ON FUNCTION public.aftercare_otp_send(text, text, text, timestamptz) TO clinic_app;--> statement-breakpoint

-- Verify an OTP: a wrong code counts; the 5th locks for 15 min and clears the code; a match opens a 30-minute session (never past the
-- link's expiry). Refusals return normally so the attempt count commits.
CREATE FUNCTION public.aftercare_otp_verify(p_token_hash text, p_otp_hash text, p_session_hash text, p_now timestamptz DEFAULT NULL) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  n public.aftercare_notices;
  v_now timestamptz := coalesce(p_now, clock_timestamp());
  v_attempts integer;
BEGIN
  IF public.app_tenant_id() IS NOT NULL THEN
    RAISE EXCEPTION 'ERR_FORBIDDEN: the aftercare page is unbound' USING ERRCODE = '42501';
  END IF;
  IF p_otp_hash IS NULL OR p_otp_hash !~ '^[0-9a-f]{64}$' OR p_session_hash IS NULL OR p_session_hash !~ '^[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: otp' USING ERRCODE = '22023';
  END IF;
  n := public.aftercare_notice_of(p_token_hash);
  IF n.id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'not_found');
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('staff_access:' || n.tenant_id::text, 0));
  SELECT * INTO n FROM public.aftercare_notices x WHERE x.tenant_id = n.tenant_id AND x.id = n.id FOR UPDATE;
  IF n.expires_at <= v_now THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'link_expired');
  END IF;
  IF n.otp_locked_until > v_now THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'otp_locked');
  END IF;
  IF n.otp_hash IS NULL OR n.otp_expires_at <= v_now THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'otp_expired');
  END IF;
  IF n.otp_hash <> p_otp_hash THEN
    v_attempts := n.otp_attempts + 1;
    IF v_attempts >= 5 THEN
      UPDATE public.aftercare_notices SET otp_attempts = 5, otp_locked_until = v_now + interval '15 minutes', otp_hash = NULL, otp_expires_at = NULL
       WHERE tenant_id = n.tenant_id AND id = n.id;
      RETURN jsonb_build_object('ok', false, 'reason', 'otp_locked', 'attempts_remaining', 0);
    END IF;
    UPDATE public.aftercare_notices SET otp_attempts = v_attempts WHERE tenant_id = n.tenant_id AND id = n.id;
    RETURN jsonb_build_object('ok', false, 'reason', 'otp_invalid', 'attempts_remaining', 5 - v_attempts);
  END IF;
  UPDATE public.aftercare_notices SET otp_hash = NULL, otp_expires_at = NULL, otp_attempts = 0, opened_at = coalesce(opened_at, v_now),
         session_hash = p_session_hash, session_expires_at = least(expires_at, v_now + interval '30 minutes')
   WHERE tenant_id = n.tenant_id AND id = n.id;
  RETURN jsonb_build_object('ok', true);
END
$$;--> statement-breakpoint
REVOKE ALL ON FUNCTION public.aftercare_otp_verify(text, text, text, timestamptz) FROM PUBLIC;--> statement-breakpoint
GRANT EXECUTE ON FUNCTION public.aftercare_otp_verify(text, text, text, timestamptz) TO clinic_app;
