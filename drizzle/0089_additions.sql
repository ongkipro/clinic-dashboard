-- Lepas Sebelum Bayar (PR-15, BILL-3, BILL-22, B-18): FO/cashier or a manager at the visit's branch releases an approved
-- addition of an open visit to start before payment, naming the staff accountable for collecting (FO/cashier or a
-- manager of the branch with an active membership now). The patient agreement in force (the plan's active consent,
-- covering it) and the authorizing clinician are recorded with it. No amount limit, no manager approval. Lock order:
-- staff_access → visit → plan → plan item → request. p: {collector_staff_id}. Returns the release id.
CREATE FUNCTION public.addition_release(p_key text, p_plan_item uuid, p jsonb) RETURNS uuid
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  a record := public.tenant_actor_lock();
  t0 public.plan_items;
  t public.plan_items;
  c public.care_plans;
  v public.visits;
  q public.clinical_requests;
  k public.procedure_consents;
  v_collector uuid;
  v_id uuid;
BEGIN
  IF a.role NOT IN ('fo_cashier','manager') THEN
    RAISE EXCEPTION 'ERR_FORBIDDEN: role may not release an addition' USING ERRCODE = '42501';
  END IF;
  IF NOT public.tenant_capability('cashier') THEN
    RAISE EXCEPTION 'ERR_TENANT_SUSPENDED: the cashier is not available now' USING ERRCODE = '42501';
  END IF;
  IF a.branch_id IS NULL THEN
    RAISE EXCEPTION 'ERR_FORBIDDEN: an active branch is needed' USING ERRCODE = '42501';
  END IF;
  IF jsonb_typeof(p) IS DISTINCT FROM 'object' OR p - 'collector_staff_id' <> '{}'::jsonb OR coalesce(p ->> 'collector_staff_id', '') !~ '^[0-9a-fA-F-]{36}$' THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: collector' USING ERRCODE = '22023';
  END IF;
  v_collector := (p ->> 'collector_staff_id')::uuid;
  -- The addition's request names its visit; lock the visit first, then the plan, the item and the request.
  SELECT x.* INTO t0 FROM public.plan_items x WHERE x.tenant_id = a.tenant_id AND x.id = p_plan_item;
  SELECT x.* INTO q FROM public.clinical_requests x WHERE x.tenant_id = a.tenant_id AND x.id = t0.request_id;
  SELECT x.* INTO v FROM public.visits x WHERE x.tenant_id = a.tenant_id AND x.id = q.visit_id AND x.branch_id = a.branch_id FOR UPDATE;
  IF t0.id IS NULL OR q.id IS NULL OR v.id IS NULL OR NOT public.app_branch_allowed(v.branch_id) THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: addition not found' USING ERRCODE = 'P0002';
  END IF;
  SELECT x.* INTO c FROM public.care_plans x WHERE x.tenant_id = v.tenant_id AND x.id = t0.plan_id FOR UPDATE;
  SELECT x.* INTO t FROM public.plan_items x WHERE x.tenant_id = v.tenant_id AND x.id = p_plan_item FOR UPDATE;
  SELECT x.* INTO q FROM public.clinical_requests x WHERE x.tenant_id = v.tenant_id AND x.id = t.request_id FOR UPDATE;
  IF NOT public.addition_of_visit(v.tenant_id, v.id, t.id) THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: addition not found' USING ERRCODE = 'P0002';
  END IF;
  IF v.closed_at IS NOT NULL THEN
    RAISE EXCEPTION 'ERR_VERSION_CONFLICT: visit_closed' USING ERRCODE = '55000';
  END IF;
  IF c.state <> 'active' THEN
    RAISE EXCEPTION 'ERR_VERSION_CONFLICT: plan_not_active' USING ERRCODE = '55000';
  END IF;
  IF EXISTS (SELECT 1 FROM public.addition_releases x WHERE x.tenant_id = v.tenant_id AND x.plan_item_id = t.id) THEN
    RAISE EXCEPTION 'ERR_VERSION_CONFLICT: addition_already_released' USING ERRCODE = '55000';
  END IF;
  -- The patient agreement (PR-11, CLIN-022): the plan's active consent covers the plan with the addition.
  SELECT x.* INTO k FROM public.procedure_consents x WHERE x.tenant_id = c.tenant_id AND x.plan_id = c.id AND x.state = 'active';
  IF k.id IS NULL OR public.consent_state(c.tenant_id, c.id) <> 'active' THEN
    RAISE EXCEPTION 'ERR_VERSION_CONFLICT: consent_not_active' USING ERRCODE = '55000';
  END IF;
  IF NOT (public.consent_staff_role(v.tenant_id, v_collector, v.branch_id, 'fo_cashier') OR public.consent_staff_role(v.tenant_id, v_collector, v.branch_id, 'manager')) THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: collector' USING ERRCODE = '22023';
  END IF;
  BEGIN
    INSERT INTO public.addition_releases (tenant_id, branch_id, visit_id, plan_item_id, request_id, authorized_by, consent_id, collector_staff_id,
                                          released_by, released_as, command_key)
    VALUES (v.tenant_id, v.branch_id, v.id, t.id, q.id, q.decided_by, k.id, v_collector, a.staff_id, a.role, p_key)
    RETURNING id INTO v_id;
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'ERR_IDEMPOTENCY_CONFLICT: a release with this key exists' USING ERRCODE = '23505';
  END;
  PERFORM public.audit_append('approval', 'addition_release', v_id, 'success', 'addition_released');
  INSERT INTO public.domain_events (tenant_id, branch_id, type, aggregate_kind, aggregate_id, staff_id, acting_role, payload)
  VALUES (v.tenant_id, v.branch_id, 'AdditionReleasedBeforePayment', 'addition_release', v_id, a.staff_id, a.role,
          jsonb_build_object('release_id', v_id, 'visit_id', v.id, 'plan_item_id', t.id, 'collector_staff_id', v_collector));
  RETURN v_id;
END
