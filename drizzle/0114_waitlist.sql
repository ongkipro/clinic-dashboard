-- The reader (plan r1 §2): a branch's open entries (and an item filter), oldest first; the patient's name and MRN for these roles (all of
-- them work the waitlist); the offered slot's start. No clinical content. Bound; the actor lock first.
CREATE FUNCTION public.waitlist_list(p_branch uuid, p_item uuid DEFAULT NULL) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
