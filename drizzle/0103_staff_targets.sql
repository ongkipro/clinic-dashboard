-- K19 closing value (r1 P1-1, D-07): actual payments in [p_from, p_to) on lines the BC closed (an issued, non-counter, non-consultation
-- invoice whose active attribution names the BC as closing; the item's scope has closing_bc; the line not written off), net of VAT, less the
-- reductions in the window (paid refunds; interrupted moves; cheaper substitutions; package closes: the unused value), clamped at 0. With
-- p_branch: only sales of that branch (the sold branch).
CREATE FUNCTION public.target_closing_value(p_tenant uuid, p_staff uuid, p_from timestamptz, p_to timestamptz, p_branch uuid DEFAULT NULL) RETURNS bigint
LANGUAGE sql STABLE SET search_path = pg_catalog, pg_temp AS $$
  WITH lines AS (
    SELECT l.* FROM public.invoice_lines l JOIN public.invoices i ON i.tenant_id = l.tenant_id AND i.id = l.invoice_id
     WHERE i.tenant_id = p_tenant AND i.state = 'issued' AND NOT i.counter AND NOT i.consultation
       AND (p_branch IS NULL OR i.sold_branch_id = p_branch)
       AND 'closing_bc' = ANY (public.commission_item_scopes(l.tenant_id, l.catalog_version_id))
       AND EXISTS (SELECT 1 FROM public.commission_sale_attributions sa WHERE sa.tenant_id = i.tenant_id AND sa.invoice_id = i.id AND sa.state = 'active'
                     AND sa.closing_bc_staff_id = p_staff)
       AND NOT EXISTS (SELECT 1 FROM public.receivable_lines rl JOIN public.write_offs w ON w.tenant_id = rl.tenant_id AND w.receivable_id = rl.receivable_id
                        WHERE rl.tenant_id = l.tenant_id AND rl.invoice_line_id = l.id)
  ), flows AS (
    -- inflows: allocations (not simulated), applied deposits, the receivable share collected in the window
    SELECT (SELECT coalesce(sum(a.amount - a.vat_portion), 0) FROM public.payment_allocations a
             WHERE a.tenant_id = l.tenant_id AND a.invoice_line_id = l.id AND NOT a.is_simulated AND a.created_at >= p_from AND a.created_at < p_to)
         + (SELECT coalesce(sum(d.amount - d.vat_amount), 0) FROM public.booking_deposits d
             WHERE d.tenant_id = l.tenant_id AND d.applied_line_id = l.id AND d.state = 'applied' AND d.decided_at >= p_from AND d.decided_at < p_to)
         + coalesce((SELECT sum(public.target_net(public.target_collected_share(rl.tenant_id, rl.receivable_id, rl.invoice_line_id, p_to)
                                                 - public.target_collected_share(rl.tenant_id, rl.receivable_id, rl.invoice_line_id, p_from), l))
                       FROM public.receivable_lines rl WHERE rl.tenant_id = l.tenant_id AND rl.invoice_line_id = l.id), 0)
         -- reductions: paid refunds; interrupted moves of an execution matched to this line; cheaper substitutions; package closes
         - (SELECT coalesce(sum(r.amount - r.vat_reversed), 0) FROM public.refunds r
             WHERE r.tenant_id = l.tenant_id AND r.invoice_line_id = l.id AND r.state = 'paid' AND r.paid_at >= p_from AND r.paid_at < p_to)
         - coalesce((SELECT sum(public.target_net(b.amount, l)) FROM public.balance_entries b
                       JOIN public.treatment_executions e ON e.tenant_id = b.tenant_id AND e.id = b.source_id
                       JOIN public.invoices i ON i.tenant_id = l.tenant_id AND i.id = l.invoice_id
                      WHERE b.tenant_id = l.tenant_id AND b.kind = 'from_interrupted_treatment' AND b.source_kind = 'treatment_execution'
                        AND b.created_at >= p_from AND b.created_at < p_to AND e.visit_id = i.visit_id AND l.substitution_id IS NULL
                        AND (l.plan_item_id = e.plan_item_id OR l.plan_item_id IS NULL AND l.item_id = public.package_plan_service(e.tenant_id, e.plan_item_id)
                                                                AND NOT public.addition_of_visit(e.tenant_id, e.visit_id, e.plan_item_id))), 0)
         - coalesce((SELECT sum(public.target_net(-ps.difference, l)) FROM public.package_substitutions ps JOIN public.packages pk ON pk.tenant_id = ps.tenant_id AND pk.id = ps.package_id
                      WHERE pk.tenant_id = l.tenant_id AND pk.invoice_line_id = l.id AND ps.state = 'approved' AND ps.difference < 0
                        AND ps.decided_at >= p_from AND ps.decided_at < p_to), 0)
         - coalesce((SELECT sum(public.target_net(greatest(0, public.package_paid(pk)
                                   - (SELECT coalesce(sum(s.allocated_value), 0) FROM public.package_sessions s WHERE s.tenant_id = pk.tenant_id AND s.package_id = pk.id AND s.state = 'redeemed')), l))
                       FROM public.packages pk WHERE pk.tenant_id = l.tenant_id AND pk.invoice_line_id = l.id AND pk.state IN ('expired','cancelled')
                        AND pk.closed_at >= p_from AND pk.closed_at < p_to), 0) AS net
      FROM lines l
  )
  SELECT greatest(0, coalesce(sum(net), 0))::bigint FROM flows
$$;--> statement-breakpoint
