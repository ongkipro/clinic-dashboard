-- The projection (P2-1 (2)/(3)): titles from rule codes only (no plan item, service or condition names, W-10); marketing identity only with
-- marketing_wa consent on the cluster (else promo_blocked "Tidak ada persetujuan promosi", UX-18); auditor masked (MRN tail, no name / phone
