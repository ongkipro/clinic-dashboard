-- After an offer: booked with the patient's own live appointment for the same service at the same branch, or declined (back to waiting).
-- p_offered names the offer the caller decides on (review r1 P1: a delayed decision for an earlier offer must not decide a newer one).
CREATE FUNCTION public.waitlist_offer_outcome(p_entry uuid, p_offered uuid, p_booked_appointment uuid) RETURNS text
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  a record := public.waitlist_actor(ARRAY['owner','admin_pusat','manager','fo_cashier','central_cs']);
  w public.waitlist_entries := public.waitlist_entry_for(a, p_entry);
  ap public.appointments;
BEGIN
  IF w.state <> 'offered' THEN
    RAISE EXCEPTION 'ERR_VERSION_CONFLICT: not_offered' USING ERRCODE = '55000';
  END IF;
  IF p_offered IS NULL OR w.offered_appointment_id <> p_offered THEN
    RAISE EXCEPTION 'ERR_VERSION_CONFLICT: offer_changed' USING ERRCODE = '55000';
  END IF;
  IF p_booked_appointment IS NULL THEN
    UPDATE public.waitlist_entries SET state = 'waiting', offered_appointment_id = NULL, offered_at = NULL WHERE tenant_id = w.tenant_id AND id = w.id;
    PERFORM public.audit_append('settings_change', 'waitlist_entry', w.id, 'success', 'waitlist_offer_declined');
    RETURN 'waiting';
  END IF;
  SELECT * INTO ap FROM public.appointments x WHERE x.tenant_id = w.tenant_id AND x.id = p_booked_appointment;
  IF ap.id IS NULL OR ap.branch_id <> w.branch_id OR public.patient_canonical(ap.tenant_id, ap.patient_id) <> public.patient_canonical(w.tenant_id, w.patient_id)
     OR NOT EXISTS (SELECT 1 FROM public.catalog_versions v WHERE v.tenant_id = ap.tenant_id AND v.id = ap.catalog_version_id AND v.item_id = w.item_id)
     OR NOT public.appointment_live(ap) THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: booked_appointment' USING ERRCODE = '22023';
  END IF;
  UPDATE public.waitlist_entries SET state = 'booked', booked_appointment_id = ap.id, offered_appointment_id = NULL, offered_at = NULL,
         closed_by = a.staff_id, closed_as = a.role, closed_at = clock_timestamp(), close_reason = 'booked'
   WHERE tenant_id = w.tenant_id AND id = w.id;
  PERFORM public.audit_append('settings_change', 'waitlist_entry', w.id, 'success', 'waitlist_booked');
  RETURN 'booked';
END
$$;--> statement-breakpoint
