-- Accounts: never deleted; open at 0, version 0, for a patient that is not merged away; identity frozen; the balance
-- changes only to the newest entry's balance_after (from the old balance), version + 1 (the 0077 pattern).
CREATE FUNCTION public.balance_accounts_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  e public.balance_entries;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('staff_access:' || coalesce(NEW.tenant_id, OLD.tenant_id)::text, 0));
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'balance accounts are never deleted' USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.balance <> 0 OR NEW.version <> 0 OR public.patient_is_merged(NEW.tenant_id, NEW.patient_id) THEN
      RAISE EXCEPTION 'an account opens at 0 for a patient that is not merged away' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
  END IF;
  IF (NEW.id, NEW.tenant_id, NEW.patient_id, NEW.created_at) IS DISTINCT FROM (OLD.id, OLD.tenant_id, OLD.patient_id, OLD.created_at)
     OR NEW.version <> OLD.version + 1 THEN
    RAISE EXCEPTION 'an account keeps its identity; each change is one version' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO e FROM public.balance_entries x WHERE x.tenant_id = NEW.tenant_id AND x.account_id = NEW.id ORDER BY x.seq DESC LIMIT 1;
  IF e.id IS NULL OR e.balance_after <> NEW.balance OR e.balance_after - e.amount <> OLD.balance THEN
    RAISE EXCEPTION 'an account balance changes only by its newest entry' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END
$$;--> statement-breakpoint
