    RAISE EXCEPTION 'ERR_TENANT_SUSPENDED: configuration is not available now' USING ERRCODE = '42501';
  END IF;
  SELECT x.id INTO v_id FROM public.staff_targets x WHERE x.tenant_id = a.tenant_id AND x.command_key = p_key;
  IF v_id IS NOT NULL THEN
    RETURN v_id;
  END IF;
  IF coalesce(p_key, '') !~ '^[A-Za-z0-9_.:-]{8,128}$' OR jsonb_typeof(p) IS DISTINCT FROM 'object' OR p - 'closing_value_target' - 'plans_target' <> '{}'::jsonb
     OR jsonb_typeof(p -> 'closing_value_target') IS DISTINCT FROM 'number' OR p ? 'plans_target' AND jsonb_typeof(p -> 'plans_target') NOT IN ('number','null') THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: target' USING ERRCODE = '22023';
  END IF;
  IF p_period IS NULL THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: period' USING ERRCODE = '22023';
  END IF;
  w := public.target_period(p_period);
  IF NOT EXISTS (SELECT 1 FROM public.staff s WHERE s.tenant_id = a.tenant_id AND s.id = p_staff) THEN
    RAISE EXCEPTION 'ERR_NOT_FOUND: staff not found' USING ERRCODE = 'P0002';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.staff_roles r WHERE r.tenant_id = a.tenant_id AND r.staff_id = p_staff AND r.role = 'bc') THEN
    RAISE EXCEPTION 'ERR_INVALID_INPUT: not_a_bc' USING ERRCODE = '22023';
  END IF;
  UPDATE public.staff_targets SET state = 'superseded', superseded_at = clock_timestamp()
   WHERE tenant_id = a.tenant_id AND staff_id = p_staff AND period_key = w.period_key AND state = 'active';
  INSERT INTO public.staff_targets (tenant_id, staff_id, period_kind, period_key, closing_value_target, plans_target, set_by, set_as, command_key)
  VALUES (a.tenant_id, p_staff, w.period_kind, w.period_key, (p ->> 'closing_value_target')::bigint, (p ->> 'plans_target')::integer, a.staff_id, a.role, p_key)
  RETURNING id INTO v_id;
  PERFORM public.audit_append('settings_change', 'staff_target', v_id, 'success', 'staff_target_set');
  RETURN v_id;
EXCEPTION WHEN check_violation OR numeric_value_out_of_range OR invalid_text_representation THEN
  RAISE EXCEPTION 'ERR_INVALID_INPUT: target' USING ERRCODE = '22023';
END
$$;--> statement-breakpoint
