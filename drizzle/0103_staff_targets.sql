-- The scorecard of a staff member over [p_from, p_to) (r1 P2-1; 19:157): completed services (finished, counted executions they performed),
-- commission gross / adjustments / net, rostered minutes (work less breaks, leave dates excluded) and executed minutes, utilisation (K15)
-- in basis points (NULL when nothing is rostered).
CREATE FUNCTION public.target_scorecard(p_tenant uuid, p_staff uuid, p_from timestamptz, p_to timestamptz) RETURNS jsonb
LANGUAGE sql STABLE SET search_path = pg_catalog, pg_temp AS $$
  WITH ex AS (
    SELECT count(*) FILTER (WHERE e.counted)::integer AS done,
           coalesce(sum(greatest(0, extract(epoch FROM (e.finished_at - e.started_at)))::bigint / 60) FILTER (WHERE e.counted), 0)::bigint AS minutes
      FROM public.treatment_executions e
     WHERE e.tenant_id = p_tenant AND e.performer_staff_id = p_staff AND e.state = 'finished' AND e.finished_at >= p_from AND e.finished_at < p_to
  ), ro AS (
    SELECT coalesce(sum(CASE WHEN s.kind = 'work' THEN 1 ELSE -1 END
                        * (extract(epoch FROM public.roster_instant(s.shift_date, s.ends, b.timezone) - public.roster_instant(s.shift_date, s.starts, b.timezone)))::bigint / 60), 0)::bigint AS minutes
      FROM public.staff_shifts s JOIN public.branches b ON b.tenant_id = s.tenant_id AND b.id = s.branch_id
     WHERE s.tenant_id = p_tenant AND s.staff_id = p_staff
       AND public.roster_instant(s.shift_date, s.starts, b.timezone) >= p_from AND public.roster_instant(s.shift_date, s.starts, b.timezone) < p_to
       AND NOT EXISTS (SELECT 1 FROM public.staff_leave lv WHERE lv.tenant_id = s.tenant_id AND lv.staff_id = s.staff_id AND lv.cancelled_at IS NULL
                         AND s.shift_date BETWEEN lv.from_date AND lv.to_date)
  ), cm AS (
    SELECT (SELECT coalesce(sum(en.amount), 0) FROM public.commission_entitlements en
             WHERE en.tenant_id = p_tenant AND en.staff_id = p_staff AND en.accrued_at >= p_from AND en.accrued_at < p_to)::bigint AS gross,
           (SELECT coalesce(sum(x.amount), 0) FROM public.commission_adjustments x
             WHERE x.tenant_id = p_tenant AND x.staff_id = p_staff AND x.adjusted_at >= p_from AND x.adjusted_at < p_to)::bigint AS adj
  )
  SELECT jsonb_build_object('completed_services', ex.done, 'executed_minutes', ex.minutes, 'rostered_minutes', greatest(ro.minutes, 0),
           'utilization_bps', CASE WHEN ro.minutes > 0 THEN (ex.minutes * 10000 / ro.minutes) END,
           'commission_gross', cm.gross, 'commission_adjustments', cm.adj, 'commission_net', cm.gross + cm.adj)
    FROM ex, ro, cm
$$;--> statement-breakpoint
